static void oled_cmd(uint8_t cmd) {
    uint8_t buf[2] = {0x80, cmd};
    i2c_write_blocking(I2C_PORT, OLED_ADDR, buf, 2, false);
}

static void oled_init(void) {
    static const uint8_t cmds[] = {
        0xAE,       /* display off */
        0x20, 0x00, /* horizontal addressing */
        0x40,       /* start line 0 */
        0xA1,       /* segment remap */
        0xA8, OLED_HEIGHT - 1,
        0xC8,       /* COM scan direction, bottom-up */
        0xD3, 0x00, /* no display offset */
        0xDA, 0x12, /* COM pins: 0x12 for 128x64, 0x02 for 128x32 */
        0xD5, 0x80, /* clock */
        0xD9, 0xF1, /* precharge */
        0xDB, 0x40, /* VCOMH */
        0x81, 0xCF, /* contrast */
        0x8D, 0x14, /* charge pump on */
        0xA4,       /* follow RAM */
        0xA6,       /* normal (not inverted) */
        0x2E,       /* deactivate scroll */
        0xAF,       /* display on */
    };

    for (size_t i = 0; i < count_of(cmds); i++) {
        oled_cmd(cmds[i]);
    }
}

static void oled_show(void) {
    oled_cmd(0x21);
    oled_cmd(0);
    oled_cmd(OLED_WIDTH - 1);
    oled_cmd(0x22);
    oled_cmd(0);
    oled_cmd(OLED_PAGES - 1);

    uint8_t packet[1 + FB_SIZE];
    packet[0] = 0x40;
    memcpy(&packet[1], framebuffer, FB_SIZE);
    i2c_write_blocking(I2C_PORT, OLED_ADDR, packet, sizeof(packet), false);
}

static void oled_clear(void) {
    memset(framebuffer, 0, FB_SIZE);
}

static void oled_pixel(int x, int y, bool on) {
    if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) {
        return;
    }

    uint8_t *byte = &framebuffer[x + (y / 8) * OLED_WIDTH];
    uint8_t mask = 1u << (y & 7);
    if (on) {
        *byte |= mask;
    } else {
        *byte &= (uint8_t)~mask;
    }
}

static void oled_char(int x, int y, char c) {
    if (c < ' ' || c > '~') {
        c = '?';
    }

    const uint8_t *glyph = font5x7[c - ' '];
    for (int col = 0; col < 5; col++) {
        uint8_t bits = glyph[col];
        for (int row = 0; row < 7; row++) {
            oled_pixel(x + col, y + row, (bits >> row) & 1);
        }
    }
}

static void oled_text(int x, int y, const char *s) {
    while (*s) {
        oled_char(x, y, *s++);
        x += 6;
    }
}

int main(void) {
    stdio_init_all();

    i2c_init(I2C_PORT, 400 * 1000);
    gpio_set_function(I2C_SDA_PIN, GPIO_FUNC_I2C);
    gpio_set_function(I2C_SCL_PIN, GPIO_FUNC_I2C);
    gpio_pull_up(I2C_SDA_PIN);
    gpio_pull_up(I2C_SCL_PIN);

    oled_init();
    oled_clear();

    const char *msg = "Hello, world!";
    int text_width = (int)strlen(msg) * 6 - 1;
    int x = (OLED_WIDTH - text_width) / 2;
    int y = (OLED_HEIGHT - 7) / 2;
    oled_text(x, y, msg);
    oled_show();

    while (true) {
        tight_loop_contents();
    }
}
